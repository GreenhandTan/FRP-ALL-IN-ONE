export let lang = localStorage.getItem("lang") || "zh";

export function setLang(newLang) {
  lang = newLang;
  localStorage.setItem("lang", lang);
}

export function t(key) {
  const keys = key.split(".");
  let obj = TRANSLATIONS[lang];
  for (const k of keys) {
    if (obj == null) return key;
    obj = obj[k];
  }
  return obj ?? key;
}
